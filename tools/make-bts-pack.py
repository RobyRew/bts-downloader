#!/usr/bin/env python3
"""Emit a BlockTheSpot [Buffer_modify] pack that flips Remote Config defaults.

BlockTheSpot reads config.ini at load time and, for every file listed under
[Buffer_modify], applies hex signature/value replacements to the buffer the CEF
zip reader returns. The value may be no longer than the signature, so this tool
only performs equal-length edits: it rewrites "default:!1" / "default:!0" inside
one flag definition.

Precedence in the client is local override -> remote value -> default. This pack
changes the default only; if the server sends a value for the property, the pack
has no effect.

Usage:
  make-bts-pack.py <dir-with-extracted-xpui> <flag> [<flag> ...]
                   [--to true|false] [--start N]
  make-bts-pack.py <dir-with-extracted-xpui> --list [--filter REGEX]

<dir> is the extracted contents of xpui.spa (the .js files sit at its top level).
File names in the output are zip entry names, which is what BTS matches.
"""
import glob
import os
import re
import sys

DEFAULT_FILTER = r'download|offline|capabilit'


def hexs(b):
    return ' '.join('%02X' % x for x in b)


def list_flags(directory, pattern):
    rx = re.compile(rb'name:"([^"]+)",description:"([^"]*)",default:(!0|!1)')
    seen = {}
    for path in sorted(glob.glob(os.path.join(directory, '*.js'))):
        data = open(path, 'rb').read()
        for m in rx.finditer(data):
            name = m.group(1).decode()
            if not re.search(pattern, name, re.I):
                continue
            seen.setdefault(name, (m.group(3).decode(), m.group(2).decode()))
    for name, (default, desc) in sorted(seen.items()):
        print('%-52s default:%-3s %s' % (name, default, desc))


def make_pack(directory, flags, to_true, start, mod_mode=False, version=''):
    want = b'!0' if to_true else b'!1'
    files = {}          # file name -> list of (group name, signature, value)
    n = 0
    for flag in flags:
        rx = re.compile(
            rb'name:"' + re.escape(flag.encode()) + rb'"[^}]{0,600}?default:(!0|!1)')
        found = False
        for path in sorted(glob.glob(os.path.join(directory, '*.js'))):
            data = open(path, 'rb').read()
            for m in rx.finditer(data):
                found = True
                if m.group(1) == want:
                    continue
                sig = m.group(0)
                val = sig[:m.start(1) - m.start()] + want
                n += 1
                files.setdefault(os.path.basename(path), []).append(
                    ('%s-%d' % (flag, n), sig, val))
        if not found:
            print('warning: no definition of %r found under %s'
                  % (flag, directory), file=sys.stderr)

    if not files:
        print('nothing to patch', file=sys.stderr)
        return 1

    print('; generated by make-bts-pack.py')
    if mod_mode:
        print('; standalone declarative mod for the experimental bts-loader (patches/)')
        print()
        print('[Compatibility]')
        print('Spotify=%s' % version)
        print()
        print('[Mod]')
        print('Enable=1')
        print()
    else:
        print('; append below the existing entries and keep the numbering continuous')
    print('[Buffer_modify]')
    if mod_mode:
        print('Enable=1')
    idx = start
    for name in files:
        print('%d=%s' % (idx, name))
        idx += 1

    for name, items in files.items():
        print()
        print('[%s]' % name)
        for i, (group, _s, _v) in enumerate(items, 1):
            print('%d=%s' % (i, group))

    for name, items in files.items():
        for group, sig, val in items:
            print()
            print('[%s]' % group)
            print('Signature_1=%s' % hexs(sig))
            print('Offset_1=0')
            print('Value_1=%s' % hexs(val))
    return 0


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 2
    directory = args[0]
    rest = args[1:]

    flags, to_true, start, list_mode, filt = [], True, 10, False, DEFAULT_FILTER
    mod_mode, version, start_set = False, '', False
    i = 0
    while i < len(rest):
        a = rest[i]
        if a == '--list':
            list_mode = True
            i += 1
        elif a == '--mod':
            mod_mode = True
            i += 1
        elif a == '--version':
            version = rest[i + 1]
            i += 2
        elif a == '--to':
            to_true = rest[i + 1].lower() != 'false'
            i += 2
        elif a == '--start':
            start = int(rest[i + 1])
            start_set = True
            i += 2
        elif a == '--filter':
            filt = rest[i + 1]
            i += 2
        else:
            flags.append(a)
            i += 1

    if list_mode:
        list_flags(directory, filt)
        return 0
    if not flags:
        print(__doc__)
        return 2
    if mod_mode and not version:
        print('--mod needs --version <x.y.z>', file=sys.stderr)
        return 2
    if mod_mode and not start_set:
        start = 1
    return make_pack(directory, flags, to_true, start, mod_mode, version)


if __name__ == '__main__':
    sys.exit(main())
